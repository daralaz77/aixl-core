"""A/B of the learned registry (P0 curated only vs P1 learned concepts exposed) and of the normal form on blind5. Reads stored responses only.
Criteria are the ones in docs/adr/ADR-021-prereg-blind5.md.   python benchmarks/atoms_ab_eval.py"""
import collections
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from atoms_freeze import check as freeze_check
from atoms_gold import D, load
from atoms_sources import texts

from aixl.atoms import fidelity
from aixl.atoms import llm_extract as LX

SET = "blind5"


def resp(variant, model):
    p = LX.Parsed()
    for h in (1, 2):
        f = os.path.join(D, "llm", f"resp_{SET}_{variant}_{model}_{h}.txt")
        part = ids[:75] if h == 1 else ids[75:]
        r = LX.parse_response(open(f, encoding="utf-8").read(), part, TX) if os.path.exists(f) else LX.Parsed(errors={i: ["NO_FILE"] for i in part})
        p.graphs.update(r.graphs); p.errors.update(r.errors)
    return p
nf = LX.normalize_graph


def cond(v, norm):
    S, O = CALLS[v]
    g = (lambda x: nf(x)) if norm else (lambda x: x)
    both = [i for i in ids if i in S.graphs and i in O.graphs]
    a = fidelity.aggregate([fidelity.score(g(S.graphs[i]), g(O.graphs[i])) for i in both])
    row = dict(valid=f"{len(S.graphs)}/{len(O.graphs)}", n=len(both), pair_exact=a["exact_graph"], pair_f1=a["overall"]["f1"], pair_core=a["core"]["f1"])
    acc = {}
    for pol in ("exact", "core"):
        accepted = {}
        for i in both:
            r = LX.decide([g(S.graphs[i]), g(O.graphs[i])], pol)
            if r.status == "ACCEPT": accepted[i] = r.graph
        acc[pol] = accepted
        row[f"accept_{pol}"] = len(accepted) / len(ids)
    # quality vs references (normalized both sides, as pre-registered)
    for pol, accepted in acc.items():
        pairs = [(nf(R[i]), nf(gr)) for i, gr in accepted.items() for R in (R_S, R_O) if i in R]
        a2 = fidelity.aggregate([fidelity.score(x, y) for x, y in pairs]) if pairs else None
        row[f"quality_{pol}_core"] = a2["core"]["f1"] if a2 and a2.get("core") else None
        row[f"quality_{pol}_exact"] = a2["exact_graph"] if a2 else None
    fps = collections.defaultdict(set)
    for i, gr in acc["core"].items(): fps[nf(gr).fingerprint(include_unrepresented=False)].add(i)
    row["collisions_core_accepted"] = sum(len(v) - 1 for v in fps.values() if len(v) > 1)
    return row, acc


R = {}


def agree(S, O, i): return nf(S.graphs[i]).fingerprint(include_unrepresented=False) == nf(O.graphs[i]).fingerprint(include_unrepresented=False)


if __name__ == "__main__":
    problems = freeze_check(SET)
    if problems:
        print(f"{SET} is VOID or not frozen yet (pre-registration, ADR-021):\n  " + "\n  ".join(problems[:12])); sys.exit(2)
    missing = [f"llm/resp_{SET}_{v}_{m}_{h}.txt" for v in ("P0", "P1") for m in ("sonnet", "opus") for h in (1, 2) if not os.path.exists(os.path.join(D, "llm", f"resp_{SET}_{v}_{m}_{h}.txt"))]
    missing += [f"annot_{SET}_{t}_*.jsonl" for t in ("S", "O") if not glob.glob(os.path.join(D, f"annot_{SET}_{t}*.jsonl"))]
    if missing:
        print(f"cannot evaluate {SET} yet: {len(missing)} expected input(s) not found under data/atoms/:\n  " + "\n  ".join(missing)); sys.exit(2)
    ids = [c["id"] for c in json.load(open(os.path.join(D, f"{SET}_cases.json"), encoding="utf-8"))]
    TX = texts(SET)
    R_S, _ = load(f"annot_{SET}_S", f"{SET}_cases.json"); R_O, _ = load(f"annot_{SET}_O", f"{SET}_cases.json")
    CALLS = {v: (resp(v, "sonnet"), resp(v, "opus")) for v in ("P0", "P1")}
    for v in ("P0", "P1"):
        for norm in (False, True): R[(v, norm)] = cond(v, norm)
    print("# A/B on blind5 (generated by benchmarks/atoms_ab_eval.py)\n")
    print("| condition | valid S/O | pair exact | pair F1 | pair core | accept exact | accept core | accepted core F1 (vs refs, normalized) | collisions |\n|---|---|---|---|---|---|---|---|---|")
    for (v, norm), (row, _) in R.items():
        qc = row["quality_core_core"]
        print(f"| {v} {'+normal form' if norm else 'raw'} | {row['valid']} | {row['pair_exact']:.3f} | {row['pair_f1']:.3f} | {row['pair_core']:.3f} | {row['accept_exact']:.1%} | {row['accept_core']:.1%} | {qc:.3f} | {row['collisions_core_accepted']} |" if qc else f"| {v} {norm} | n/a |")
    a, b = R[("P0", False)][0], R[("P0", True)][0]
    c, d = R[("P0", True)][0], R[("P1", True)][0]
    S0, O0 = CALLS["P0"]; S1, O1 = CALLS["P1"]
    common = [i for i in ids if all(i in x.graphs for x in (S0, O0, S1, O1))]
    up = sum(1 for i in common if agree(S1, O1, i) and not agree(S0, O0, i)); down = sum(1 for i in common if agree(S0, O0, i) and not agree(S1, O1, i))
    print(f"\nPaired flips on {len(common)} texts (normalized exact agreement Sonnet-vs-Opus): P1 agrees & P0 does not: {up}; P0 agrees & P1 does not: {down}.\n")
    q0, q1 = R[("P0", True)][0]["quality_core_core"], R[("P1", True)][0]["quality_core_core"]
    h = {
     "H1 normal form on P0: exact agreement +>=2 pts and core F1 drop <= 0.01": (b["pair_exact"] - a["pair_exact"] >= 0.02 and a["pair_core"] - b["pair_core"] <= 0.01, f"exact {a['pair_exact']:.3f} -> {b['pair_exact']:.3f}; core {a['pair_core']:.3f} -> {b['pair_core']:.3f}"),
     "H2 registry exposure (normalized): exact agreement +>=3 pts AND core acceptance +>=3 pts": (d["pair_exact"] - c["pair_exact"] >= 0.03 and d["accept_core"] - c["accept_core"] >= 0.03, f"exact {c['pair_exact']:.3f} -> {d['pair_exact']:.3f}; core acceptance {c['accept_core']:.1%} -> {d['accept_core']:.1%}"),
     "H3 no harm: accepted core F1 P1 >= P0 - 0.02 and collisions <= P0 + 1": (q1 is not None and q0 is not None and q1 >= q0 - 0.02 and d["collisions_core_accepted"] <= c["collisions_core_accepted"] + 1, f"accepted core F1 {q0} -> {q1}; collisions {c['collisions_core_accepted']} -> {d['collisions_core_accepted']}"),
     "H4 combined (P1 + normal form, core): acceptance >= 60 % and accepted core F1 >= 0.88": (d["accept_core"] >= 0.60 and q1 is not None and q1 >= 0.88, f"acceptance {d['accept_core']:.1%}; accepted core F1 {q1}"),
    }
    print("| pre-registered hypothesis | verdict | numbers |\n|---|---|---|")
    for k, (ok, num) in h.items(): print(f"| {k} | {'MET' if ok else 'NOT MET'} | {num} |")
