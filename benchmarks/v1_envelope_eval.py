"""Option E: (1) coverage on dev set + real traffic, (2) false alarms on benign paraphrases (EQ pairs), (3) detection on rule-made corruptions.
Mutations are generated by simple rules (own-author); this is a dev-set signal, not blind evidence."""
import re, glob, json, random, collections
import benchmarks.dataset as d
from aixl.envelope import seal, verify

# 1. benign paraphrases + 2. different-meaning pairs (dataset labels)
def run_pairs(pairs, label):
    c = collections.Counter(verify(seal(a), b) for a, b in pairs)
    print(f"{label:34} n={len(pairs):3}", dict(c))
run_pairs(d.EQ + d.NEG_EQ + d.QTY_EQ + d.DATE_EQ, "equivalent pairs (want MATCH)")
run_pairs(d.DIFF + d.NEG_NEQ + d.QTY_NEQ + d.DATE_NEQ, "different pairs (want MISMATCH)")

# 3. corruption of structured instructions
random.seed(3)
texts = sorted({x for n in ["EQ", "DIFF", "QTY_EQ", "DATE_EQ"] for a, b in getattr(d, n) for x in (a, b)})
SWAP = {"Analiza": "Elimina", "Analyze": "Delete", "Genera": "Elimina", "Envía": "Elimina", "Compara": "Elimina", "Busca": "Elimina", "Send": "Delete",
        "Translate": "Delete", "Find": "Delete", "Calcula": "Elimina", "Resume": "Elimina", "Verifica": "Elimina", "Check": "Delete", "Get": "Delete", "Crea": "Elimina", "Create": "Delete", "Ejecuta": "Elimina"}
def m_negate(t):  return ("Do not " + t[0].lower() + t[1:]) if re.match(r"[A-Za-z]", t) and t.split()[0] in ("Analyze", "Translate", "Send", "Find", "Check", "Get", "Create", "Compare", "Generate", "Summarize") else ("No " + t[0].lower() + t[1:])
def m_number(t):
    ms = list(re.finditer(r"\d+", t))
    if not ms: return None
    m = random.choice(ms); n = int(m.group()); return t[:m.start()] + str(n * 10 + 1) + t[m.end():]
def m_action(t):
    w = t.split()[0]; return (SWAP[w] + t[len(w):]) if w in SWAP else None
def m_drop_last_word(t):
    w = t.rstrip(".").split(); return " ".join(w[:-1]) + "." if len(w) > 3 else None
res = collections.defaultdict(collections.Counter)
for t in texts:
    env = seal(t)
    if not env["verifiable"]: res["(source not verifiable)"]["skipped"] += 1; continue
    for name, f in [("negation inserted", m_negate), ("number changed", m_number), ("action swapped to delete", m_action), ("last word dropped", m_drop_last_word)]:
        mt = f(t)
        if mt and mt != t: res[name][verify(env, mt)] += 1
for k, v in res.items(): print(f"{k:28}", dict(v))

# coverage on real traffic
ms = set()
for f in glob.glob("/Users/darwingperez/.claude/projects/*/*.jsonl"):
    for l in open(f, errors="ignore"):
        try: o = json.loads(l)
        except Exception: continue
        c = o.get("message", {}).get("content") if o.get("type") == "user" else None
        if isinstance(c, str):
            c = c.strip()
            if c and not c.startswith(("<", "[", "/")) and "system-reminder" not in c and "pasted_content" not in c: ms.add(c)
v = sum(seal(m)["verifiable"] for m in ms)
print(f"real traffic verifiable: {v}/{len(ms)} ({100*v/len(ms):.1f}%)  dev set: {sum(seal(t)['verifiable'] for t in texts)}/{len(texts)}")
