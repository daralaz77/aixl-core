"""Evaluate the LLM wrapper with abstention (aixl.atoms.llm_extract) on blind3. No model calls: reads stored responses.
New runs (resp_blind3_{sonnet,opus}_{1,2}.txt, produced from build_prompt) are the two 'calls'; the OLD annotations
(annot_blind3_S / annot_blind3_O, read the guide from disk) are independent references.  python benchmarks/atoms_wrapper_eval.py"""
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from atoms_gold import load, D
from aixl.atoms import fidelity, llm_extract as LX
from aixl.atoms.schema import AtomGraph

cases = json.load(open(os.path.join(D, "blind3_cases.json"), encoding="utf-8"))
ids = [c["id"] for c in cases]; texts = {c["id"]: c["text"] for c in cases}
def resp(model):
    p = LX.Parsed()
    for h in (1, 2):
        part_ids = ids[:75] if h == 1 else ids[75:]
        f = os.path.join(D, "llm", f"resp_blind3_{model}_{h}.txt")
        r = LX.parse_response(open(f, encoding="utf-8").read(), part_ids, texts) if os.path.exists(f) else LX.Parsed(errors={i: ["NO_FILE"] for i in part_ids})
        p.graphs.update(r.graphs); p.errors.update(r.errors)
    return p
NS, NO = resp("sonnet"), resp("opus")
OS, _ = load("annot_blind3_S", "blind3_cases.json"); OO, _ = load("annot_blind3_O", "blind3_cases.json")
refs = {"old-Sonnet": OS, "old-Opus": OO}

def agg(pairs):
    sc = [fidelity.score(r, g) for r, g in pairs]
    if not sc: return "-"
    a = fidelity.aggregate(sc)
    return f"exact {a['exact_graph']:.3f} | F1 {a['overall']['f1']:.3f} | core {a['core']['f1']:.3f}" if a.get("core") else f"exact {a['exact_graph']:.3f}"

print("# AIXL 0.4 LLM wrapper with abstention — evidence on blind3 (generated by benchmarks/atoms_wrapper_eval.py)\n")
print(f"prompt id `{LX.prompt_id()}` (guide + registry {LX.R.REGISTRY_VERSION}); 150 unseen texts; two independent calls per text (Sonnet, Opus).\n")
print(f"Parse/validation of the NEW calls: Sonnet valid {len(NS.graphs)}/150, Opus valid {len(NO.graphs)}/150 (invalid or missing: {len(NS.errors)} / {len(NO.errors)}).\n")
print("## Single call vs references (agreement with an independent annotation of the same text; mean over the two references)\n| call | valid n | agreement with references |\n|---|---|---|")
for nm, P in (("new Sonnet", NS), ("new Opus", NO)):
    pairs = [(R_[i], g) for i, g in P.graphs.items() for R_ in refs.values() if i in R_]
    print(f"| {nm} | {len(P.graphs)} | {agg(pairs)} |")
for pol in ("exact", "core"):
    acc, abst, inv = [], [], []
    for i in ids:
        if i not in NS.graphs or i not in NO.graphs: inv.append(i); continue
        r = LX.decide([NS.graphs[i], NO.graphs[i]], pol)
        (acc if r.status == "ACCEPT" else abst).append((i, r))
    print(f"\n## Wrapper, policy `{pol}`: ACCEPT {len(acc)} / 150 ({len(acc)/150:.1%}), ABSTAIN {len(abst)}, invalid-call {len(inv)}")
    print("| subset | n | agreement of the accepted/first graph with references |\n|---|---|---|")
    for nm, S_ in (("accepted", acc), ("abstained (first call's graph, for contrast)", abst)):
        pairs = [(R_[i], (r.graph or NS.graphs[i])) for i, r in S_ for R_ in refs.values() if i in R_]
        print(f"| {nm} | {len(S_)} | {agg(pairs)} |")
    both = [(i, r) for i, r in acc if i in OS and i in OO and OS[i].fingerprint(include_unrepresented=False) == OO[i].fingerprint(include_unrepresented=False)]
    ok = sum(1 for i, r in acc if r.graph.fingerprint(include_unrepresented=False) in (OS[i].fingerprint(include_unrepresented=False), OO[i].fingerprint(include_unrepresented=False)))
    print(f"\nAccepted graphs identical to at least one old reference: {ok}/{len(acc)} ({ok/max(len(acc),1):.1%}); " + f"identical to BOTH old references (refs agree): {sum(1 for i,r in both if r.graph.fingerprint(include_unrepresented=False)==OS[i].fingerprint(include_unrepresented=False))}/{len(both)} of the accepted where the old refs agree.")
    if pol == "core":
        aux = [i for i, r in acc if r.agreement == "core"]; print(f"Accepted by core agreement only (auxiliary links differ): {len(aux)}")
base = [(OO[i], OS[i]) for i in ids if i in OS and i in OO]
print(f"\nContext: the two OLD references agree with each other at: {agg(base)}")
