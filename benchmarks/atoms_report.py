"""Recompute EVERY number of the AIXL 0.4 atom-layer evidence from the stored annotation files (no model calls).  python benchmarks/atoms_report.py > docs/ATOMS_EVIDENCE.generated.md"""
import sys, os, json, glob
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from atoms_gold import load, D
from aixl.atoms.schema import AtomGraph
from aixl.atoms import fidelity
from aixl.atoms.extract import extract


def row(label, scores):
    a = fidelity.aggregate(scores)
    g = lambda k: f"{a[k]['f1']:.3f}" if a.get(k) else "-"
    return f"| {label} | {len(scores)} | {a['exact_graph']:.3f} | {g('overall')} | {g('core')} | {g('identity')} | {g('relation')} | {g('scope')} | {g('polarity')} | {g('quantitative')} | {g('temporal')} | {g('reference')} |"


def pair(pa, pb, cases):
    A, _ = load(pa, cases); B, _ = load(pb, cases)
    ids = sorted(set(A) & set(B))
    return [fidelity.score(A[i], B[i]) for i in ids]


def read(f):
    out = {}
    for l in open(f, encoding="utf-8"):
        r = json.loads(l); out[r["id"]] = AtomGraph.from_dict(dict(atoms=r["atoms"], relations=r["relations"], unrepresented=r.get("unrepresented", [])))
    return out


H = "| comparison | n | exact graph | overall F1 | core F1 | identity | relation | scope | polarity | quantity | time | reference |\n|---|---|---|---|---|---|---|---|---|---|---|---|"
print("# AIXL 0.4 atom layer — evidence (generated by benchmarks/atoms_report.py)\n")
print("## 1. Inter-annotator agreement (the ceiling for any extractor)\n" + H)
print(row("dev (148): Sonnet-A vs Sonnet-B (same model, correlated)", pair("annot_A", "annot_B", "cases_dev.json")))
print(row("dev (148): Sonnet vs Opus", pair("annot_A", "annot_C", "cases_dev.json")))
print(row("blind1 v0.2 guide (150): Sonnet vs Opus", pair("annot_blind1_S", "annot_blind1_O", "blind1_cases.json")))
print(row("blind1 v0.2 guide (150): Sonnet vs Haiku", pair("annot_blind1_S", "annot_blind1_H", "blind1_cases.json")))
print(row("blind1 v0.3 guide (150): Sonnet vs Opus  [guide written from these texts: contaminated]", pair("annot_b1v3_S", "annot_b1v3_O", "blind1_cases.json")))
print(row("**blind2 v0.3 guide (150, unseen): Sonnet vs Opus**", pair("annot_blind2_S", "annot_blind2_O", "blind2_cases.json")))
print(row("**blind3 v0.4 guide (150, unseen): Sonnet vs Opus**", pair("annot_blind3_S", "annot_blind3_O", "blind3_cases.json")))
print("\n## 2. Rule extractor (aixl.atoms.extract) — controlled domain, fail-closed\n" + H)
texts = {c["id"]: c for c in json.load(open(os.path.join(D, "cases_dev.json"), encoding="utf-8"))}
gold = {}
for l in open(os.path.join(D, "gold_dev.jsonl"), encoding="utf-8"):
    r = json.loads(l); gold[r["id"]] = AtomGraph.from_dict(dict(atoms=r["atoms"], relations=r["relations"]))
sc, comp = [], []
for i, g in gold.items():
    x = extract(texts[i]["text"]); s = fidelity.score(g, x); sc.append(s)
    comp.append((x.complete, s["exact"]))
print(row("dev gold (TUNED ON THIS SET: regression guard only)", sc))
print(f"\nDev: extractor declares COMPLETE on {sum(c for c,_ in comp)} of {len(comp)}; of those, exact = {sum(e for c,e in comp if c)}. Silent errors (complete but wrong): {sum(1 for c,e in comp if c and not e)}.")
for nm, pre, cf in (("blind1 (v0.2 gold: Sonnet)", "annot_blind1_S", "blind1_cases.json"), ("blind2 (Sonnet)", "annot_blind2_S", "blind2_cases.json"), ("blind3 (Sonnet)", "annot_blind3_S", "blind3_cases.json")):
    G, t = load(pre, cf)
    sc2, cc = [], []
    for i, g in G.items():
        x = extract(t[i]["text"]); sc2.append(fidelity.score(g, x)); cc.append((x.complete, sc2[-1]["exact"]))
    print(f"\n{nm}: " + row("", sc2)[3:] + f"\n   declared COMPLETE: {sum(c for c,_ in cc)} / {len(cc)}; silent errors: {sum(1 for c,e in cc if c and not e)}")
print("\n## 3. Cross-model transport through AIXL (40 blind1 cases, two directions)\n" + H)
ids = json.load(open(os.path.join(D, "interop", "ids.json")))
S, _ = load("annot_b1v3_S", "blind1_cases.json"); O, _ = load("annot_b1v3_O", "blind1_cases.json")
rSO = read(os.path.join(D, "interop", "reex_S_by_O.jsonl")); rOS = read(os.path.join(D, "interop", "reex_O_by_S.jsonl"))
print(row("baseline: Sonnet vs Opus reading the original text", [fidelity.score(S[i], O[i]) for i in ids]))
print(row("Sonnet -> AIXL -> Opus writes text -> Sonnet re-extracts, vs Sonnet's original", [fidelity.score(S[i], rSO[i]) for i in ids]))
print(row("Opus -> AIXL -> Sonnet writes text -> Opus re-extracts, vs Opus's original", [fidelity.score(O[i], rOS[i]) for i in ids]))
